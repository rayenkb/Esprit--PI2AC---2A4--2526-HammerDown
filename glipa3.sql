CREATE TABLE CLIENTS (
    CLIENT_ID           NUMBER          NOT NULL,
    FIRST_NAME          VARCHAR2(100)   NOT NULL,
    LAST_NAME           VARCHAR2(100)   NOT NULL,
    EMAIL               VARCHAR2(150),
    PHONE_NUMBER        VARCHAR2(20),
    ADDRESS             VARCHAR2(255),
    GENDER              VARCHAR2(10),
    BIRTH_DATE          DATE,
    AGE                 NUMBER,
    ACCOUNT_BALANCE     NUMBER(15,2)    DEFAULT 0,
    REGISTRATION_DATE   DATE            DEFAULT TRUNC(SYSDATE),
    STATUS              VARCHAR2(20)    DEFAULT 'Active',
    ASSIGNED_EMPLOYEE_ID NUMBER,
    CONSTRAINT PK_CLIENTS PRIMARY KEY (CLIENT_ID),
    CONSTRAINT UQ_CLIENTS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CHK_CLIENTS_STATUS CHECK (STATUS IN ('Active', 'Inactive', 'Suspended')),
    CONSTRAINT CHK_CLIENTS_GENDER CHECK (GENDER IN ('Male', 'Female', 'Other')),
    CONSTRAINT FK_CLIENTS_EMPLOYEE FOREIGN KEY (ASSIGNED_EMPLOYEE_ID)
        REFERENCES EMPLOYEES (EMPLOYEE_ID)
);
/

