CREATE TABLE ORDERS (
    ORDER_ID        NUMBER          NOT NULL,
    CLIENT_ID       NUMBER          NOT NULL,
    EMPLOYEE_ID     NUMBER          NOT NULL,
    ORDER_DATE      TIMESTAMP       DEFAULT CURRENT_TIMESTAMP,
    ORDER_TYPE      VARCHAR2(100),
    ORDER_STATUS    VARCHAR2(20)    DEFAULT 'Pending',
    TOTAL_QUANTITY  NUMBER          DEFAULT 0,
    TOTAL_PRICE     NUMBER(15,2)    DEFAULT 0,
    PAYMENT_STATUS  VARCHAR2(10)    DEFAULT 'Unpaid',
    CONSTRAINT PK_ORDERS PRIMARY KEY (ORDER_ID),
    CONSTRAINT CHK_ORDERS_PAYMENT CHECK (PAYMENT_STATUS IN ('Unpaid', 'Partial', 'Paid')),
    CONSTRAINT CHK_ORDERS_STATUS  CHECK (ORDER_STATUS IN ('Pending', 'Processing', 'Completed', 'Cancelled')),
    CONSTRAINT FK_ORDERS_CLIENT   FOREIGN KEY (CLIENT_ID)   REFERENCES CLIENTS   (CLIENT_ID),
    CONSTRAINT FK_ORDERS_EMPLOYEE FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEES (EMPLOYEE_ID)
);
/

